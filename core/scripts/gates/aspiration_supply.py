"""Aspiration-supply gate — daemon-safe, aspiration-level ( / ).

Refuses MANUFACTURED aspirations at the write chokepoint. The idle path
(aspirations-all-blocked B2 → create-aspiration from-self, B6.7 blocker
synthesis, aspirations-complete-review "replacement" generation) is the
lane where an agent with nothing to do invents work. Its quality rules —
"category labels are not evidence", "an empty pool is acceptable", the
interestingness filter — lived only as prose inside a ~1,100-line skill,
and on a real deployment (2026-09-02) they were skipped outright: five
self-generated aspirations in four days restating one idea ("build
analytical frameworks from public data while the API is blocked"),
zero interestingness-filter events logged, three of them stamped
`user_directive` by the replacement path so no gate ever looked.

This module turns the load-bearing judgments into a script-gated decision
that runs inside the daemon's aspiration add endpoint (every creation lane
funnels through it) and is also callable pre-flight from the skill via
`core/scripts/aspiration-supply-gate.py`.

Scope — fires ONLY for self-generated aspirations:
  * `origin_signal` matches a prefix in config `idle_supply.gated_origin_prefixes`
    (all_blocked_gap, idle_fallback, blocker_pattern:, successor:, ...), OR
  * the motivation is successor-shaped ("Replace(s) completed X with Y")
    under ANY origin — that shape is self-generated by construction, and
    stamping it `user_directive` is an origin misattribution (refused).
User-directed, board-derived and pending-question-derived aspirations pass
untouched (`gated: false`).

Checks on a gated aspiration (ALL must hold, else would_block):
  1. `supply_evidence` present with `gap`, `needle`, `checked` (see
     REMEDY_SHAPE) — the generator must state what is missing, what the
     user gets, and what it LOOKED AT to conclude the gap is real.
  2. ≥ N entries of `checked` resolve to things that EXIST (aspiration /
     goal ids in the store, tree node keys, files under the governed roots,
     board post / reasoning-bank / guardrail / hypothesis ids in their
     stores). Category labels and URLs are not referents.
  3. Neither the motivation's first sentence nor `gap` is blocker-shaped
     ("X is human-blocked", "awaiting approval", "until access is
     restored"). A blocked lane is a reason to WAIT, not a reason to build.
  4. Token overlap with every existing aspiration (live ∪ archive) stays
     below `overlap_threshold`. Overlap with an ACTIVE aspiration is
     refused outright ("file goals under <id>"); overlap with a
     completed/retired one is allowed only when that id is among the
     verified `checked` referents — i.e. the generator read the delivered
     work and names what it lacks (consolidate-before-expand rule 5,
     made mechanical).
  5. Per-agent daily cap on self-generated aspirations
     (`max_self_generated_per_agent_per_day`) — the juice-vs-squeeze
     backstop when everything above is overridden.

Public API:
    evaluate(asp, *, existing, tree_keys=None, override_supply=None,
             agent_name="", world_dir=None, project_root=None,
             meta_dir=None, agent_dir=None, config=None, now=None) -> dict

Return shape:
    {"would_block": bool, "gated": bool, "reason": str,
     "failures": [{"check": str, "detail": str}],
     "checks": {...per-check structured output...},
     "overlaps": [{"id", "status", "title", "containment", "shared"}],
     "remedy": str | None, "override_applied"?: str}

Side effects (inside evaluate, both best-effort):
    * override fires AND would have blocked → append one record to
      <world_dir>/aspiration-supply-overrides.jsonl
    * one _gate_log() telemetry record per gated evaluation
      (decision noop for non-gated aspirations)

Daemon safety: reads no env; every path is an explicit argument. Store
reads are plain-text presence scans (no JSON parse of foreign records).
"""
